/** 모르는 코드가 와도 화면이 비지 않게 한다. 규칙은 늘어날 수 있다. */
export function explain(code: string): RuleExplain {
  return RULE_EXPLAIN[code] ?? {
    what: '완성 기준 하나가 아직 충족되지 않았습니다.',
    why: '비운 채 내보내면 산출물에 미정으로 남습니다.',
  };
}

/**
 * 원문 한 조각을 **사람이 읽을 수 있게** 다듬는다.
 *
 * 빌더 지적(2026-09-03): 점검 목록에 `- **성능(Performance)**:` 같은 마크다운이 그대로
 * 박혀 있어 "json인지 md인지" 알아볼 수 없었다. 무엇이 문제인지 보이라고 넣은 근거가
 * 오히려 읽기를 막았다. 기호를 걷어내고 한 줄로 줄인다.
 */
export function plainExcerpt(text: string, max = 90): string {
  const flat = text
    .replace(/```[\s\S]*?```/g, ' ')          // 코드 블록
    .replace(/[*_~`>#|]/g, '')                 // 강조·인용·표·코드 기호
    .replace(/^\s*[-+]\s+/gm, '')              // 목록 머리표
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')   // 링크는 글자만
    .replace(/\s+/g, ' ')
    .trim();
  return flat.length <= max ? flat : `${flat.slice(0, max).trimEnd()}…`;
}
